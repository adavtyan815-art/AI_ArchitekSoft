export type AdminDict = typeof hy;
const dicts: Record<AdminLocale, AdminDict> = { hy, en };

export function isAdminLocale(x: unknown): x is AdminLocale {
  return x === "hy" || x === "en";
}

export async function getAdminLocale(): Promise<AdminLocale> {
  const v = (await cookies()).get(ADMIN_LANG_COOKIE)?.value;
  return isAdminLocale(v) ? v : "hy";
}

export async function getAdminDict(): Promise<{ t: AdminDict; locale: AdminLocale }> {
  const locale = await getAdminLocale();
  return { t: dicts[locale], locale };
}

export function adminDict(locale: AdminLocale): AdminDict {
  return dicts[locale];
}

/** Localised label for a status-like value from any of the dictionary groups. */
export function labelFor(t: AdminDict, group: keyof AdminDict, value: string | null | undefined): string {
  if (!value) return "—";
  const g = t[group] as unknown as Record<string, string>;
  return (g && typeof g[value] === "string" ? g[value] : value.replace(/_/g, " ")) as string;
}

/** Page-local strings: `const L = local({ hy: {...}, en: {...} }, locale)` */
export function local<T>(obj: Record<AdminLocale, T>, locale: AdminLocale): T {
  return obj[locale] ?? obj.hy;
}
